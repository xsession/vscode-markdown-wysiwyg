const assert = require('assert');
const {listeningDocument, nextHeading} = require('../out/listeningDocument');
const doc = listeningDocument('---\ntitle: hidden\n---\n# Guide\n\nFirst sentence. Second sentence.\n\n## Wiring\n\nConnect the board.\n\n```c\nint secret;\n```\n\n| Pin | Function |\n| --- | --- |\n| 3 | UART |\n\n![Board](board.png)');
assert.strictEqual(doc.headings.length, 2);
assert.strictEqual(doc.segments.filter(s => s.kind === 'sentence').length, 3);
assert(doc.segments.some(s => s.text === 'Code block skipped.'));
assert(!doc.segments.some(s => s.text.includes('secret')));
assert(doc.segments.some(s => s.text.includes('Pin: 3') && s.text.includes('Function: UART')));
assert(doc.segments.some(s => s.kind === 'image' && s.text.includes('Board')));
assert.deepStrictEqual(doc.segments.find(s => s.text.startsWith('Connect')).path, ['Guide', 'Wiring']);
assert.strictEqual(nextHeading(doc, 0), doc.headings[1].index);
assert.strictEqual(nextHeading(doc, doc.headings[1].index, true), 0);
assert.strictEqual(listeningDocument('Title\n=====\n\nParagraph.').headings[0].level, 1);
assert(!listeningDocument('<!--\n# Hidden\n-->\nVisible.').headings.length);
assert(listeningDocument('```html\n<!-- unfinished comment\n```\n\nAfter code.').segments.some(s => s.text === 'After code.'));
const huge = listeningDocument('# Long\n\n' + 'A meaningful sentence. '.repeat(40000));
assert.strictEqual(huge.segments.length, 40001);
assert(huge.segments.every(s => s.text.length <= 800));
console.log('Listening index: sentence boundaries, hierarchy, source positions, table labels, skipped code, images and 40,000-sentence document passed');
